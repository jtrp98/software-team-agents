export class CodexAdapter implements ExecutorPort {
  readonly id = "codex";
  readonly displayName = "Codex";
  readonly binding: RuntimeBinding = {
    // `.codex/agents/*.toml` is the officially documented custom-agent location
    // and schema: required `name`, `description`, `developer_instructions`.
    // The adapter reads exactly that file and folds its developer_instructions
    // into the prompt — still necessary because no exec-level named-agent
    // selector is documented (see header).
    dir: ".codex",
    definitionPath: (role) => `.codex/agents/${role}.toml`,
    // Project hooks remain intentionally untrusted. `null` says the binding
    // file itself proves no guard; guarded headless runs are certified by the
    // per-run permission profile and isolated execpolicy below.
    guardConfigPath: null,
    // Headless execution does not trust project hooks. It compiles the active
    // packet into a native permission profile and reports that exact run.
    guardEnforcement: "per-run",
  };
  readonly capabilities: ReadonlySet<RuntimeCapability> = new Set(CODEX_CAPABILITIES);
  readonly models: ReadonlySet<string>;
  readonly workspace: RuntimeWorkspace;

  private readonly spawn: SpawnSync;
  private readonly defaultTimeoutMs: number;
  private readonly outputSchema?: Record<string, unknown>;
  private readonly inheritCodexAuth: boolean;
  private readonly resolveCommand: CommandResolver;
  private readonly platform: string;
  /** V13 TASK-014 — the lifecycle port, over this adapter's one spawn-and-parse implementation. */
  private readonly lifecycle: SingleShotLifecycle;

  constructor(opts: CodexAdapterOptions) {
    this.workspace = new LocalWorkspace({ root: opts.projectRoot });
    this.spawn = opts.spawnSync ?? (nodeSpawnSync as unknown as SpawnSync);
    this.defaultTimeoutMs = opts.timeoutMs ?? 30 * 60_000;
    this.models = new Set(opts.models ?? []);
    this.outputSchema = opts.outputSchema;
    this.resolveCommand = opts.resolveCommand ?? resolveNpmCliScriptImpl;
    this.platform = opts.platform ?? process.platform;
    // Unit tests inject a fake process and must never reach into the user's
    // credential store. Production construction inherits only auth.json into
    // the isolated per-run home; config, plugins, MCPs, and user rules do not.
    this.inheritCodexAuth = opts.spawnSync === undefined;
    // No `sessionRefFrom`: no session id has been verified in the `codex exec
    // --json` event stream, so evidence records none rather than inventing one.
    this.lifecycle = new SingleShotLifecycle(this.id, { run: (req) => this.executeAgent(req), journalRoot: opts.journalRoot });
  }

  // V13 TASK-014 — the lifecycle port, delegating to the shared single-shot
  // implementation over `executeAgent`.
  prepare(req: RuntimeAgentRequest): Promise<PreparedExecutorAttempt> {
    return this.lifecycle.prepare(req);
  }
  execute(attempt: PreparedExecutorAttempt): Promise<RuntimeAgentResult> {
    return this.lifecycle.execute(attempt);
  }
  resume(ref: ExecutorAttemptRef): Promise<RuntimeAgentResult> {
    return this.lifecycle.resume(ref);
  }
  cancel(ref: ExecutorAttemptRef): Promise<ExecutorCancelOutcome> {
    return this.lifecycle.cancel(ref);
  }
  collectResult(ref: ExecutorAttemptRef): Promise<RuntimeAgentResult | null> {
    return this.lifecycle.collectResult(ref);
  }
  collectEvidence(ref: ExecutorAttemptRef): Promise<ExecutorEvidence> {
    return this.lifecycle.collectEvidence(ref);
  }

  /**
   * One spawn, plus the single retry it is allowed: on Windows an ENOENT from a
   * bare command name usually means "npm shim", not "not installed" — resolve
   * the shim's real entry script and try once more (same seam as
   * `claudeCodeAdapter.ts`). Any other error (or a resolver that finds nothing)
   * returns the first result untouched.
   */
  private spawnResolved(
    command: string,
    args: string[],
    options: Parameters<SpawnSync>[2],
  ): { proc: SpawnSyncReturns<string>; resolvedThrough: string | null } {
    const proc = this.spawn(command, args, options);
    const code = proc.error ? (proc.error as NodeJS.ErrnoException).code : undefined;
    if (code !== "ENOENT" || this.platform !== "win32") return { proc, resolvedThrough: null };
    const resolved = this.resolveCommand(command);
    if (!resolved) return { proc, resolvedThrough: null };
    return { proc: this.spawn(resolved.file, [...resolved.prefixArgs, ...args], options), resolvedThrough: resolved.file };
  }

  async probe(): Promise<RuntimeProbe> {
    let proc: SpawnSyncReturns<string>;
    try {
      ({ proc } = this.spawnResolved("codex", ["--version"], { encoding: "utf8", timeout: 10_000, maxBuffer: 1024 * 1024 }));
    } catch (e) {
      return { available: false, reason: String(e) };
    }
    if (proc.error) return { available: false, reason: proc.error.message };
    if (proc.status !== 0) return { available: false, reason: `\`codex --version\` exited ${proc.status ?? "unknown"}` };
    return { available: true, version: (proc.stdout ?? "").trim() };
  }

  async executeAgent(req: RuntimeAgentRequest): Promise<RuntimeAgentResult> {
    let invocation: CodexPermissionInvocation;
    try {
      invocation = codexPermissionInvocationFor(req);
    } catch (error) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards: guardReport(false, req.guards.exitChecks.length > 0, requiresPreToolGuard(req.guards, req.autonomy)),
        diagnostics: [
          `${CODEX_PERMISSION_PROFILE_UNAVAILABLE}: refusing guarded codex exec before spawn — ${String(error)}`,
        ],
      };
    }
    const guards = invocation.guards;

    // NAMED_AGENTS is not claimed (no documented exec-level selector): the
    // role's official `.toml` binding is read and its developer_instructions
    // folded into the prompt on every run.
    let roleDefinition: string | null;
    try {
      roleDefinition = await this.workspace.readFile(req.definitionPath);
    } catch (e) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards,
        diagnostics: [`could not read role binding ${req.definitionPath}: ${String(e)}`],
      };
    }
    if (roleDefinition === null) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards,
        diagnostics: [
          `no role binding found at ${req.definitionPath} — no exec-level named-agent flag is documented, ` +
            `so this adapter needs that file to fold into the prompt (see codexAdapter.ts header)`,
        ],
      };
    }
    const instructions = extractDeveloperInstructions(roleDefinition);
    if (instructions === null) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards,
        diagnostics: [
          `role binding ${req.definitionPath} has no developer_instructions — this binding does not match ` +
            `the generated schema (name/description/developer_instructions); regenerate it via sta init`,
        ],
      };
    }

    const prompt = `${instructions}\n\n---\n\n${req.prompt}`;

    // Tier bindings are explicit runtime choices.  Unlike role frontmatter,
    // they must become Codex CLI arguments or the run merely records the
    // intended tier while silently using Codex's configured default.
    if (req.modelExplicit && req.model && this.models.size > 0 && !this.models.has(req.model)) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards,
        diagnostics: [
          `refusing to run: model "${req.model}" is not in this workspace's configured Codex tier catalogue ` +
            `(${[...this.models].join(", ")})`,
        ],
      };
    }
    if (req.effort && !CODEX_REASONING_EFFORTS.has(req.effort)) {
      return {
        status: "ERROR",
        exitCode: null,
        text: "",
        usage: {},
        guards,
        diagnostics: [
          `refusing to run: reasoning effort "${req.effort}" is not supported by the Codex tier adapter ` +
            `(${[...CODEX_REASONING_EFFORTS].join(", ")})`,
        ],
      };
    }

    let runHome: PreparedCodexHome | null = null;
    if (requiresPreToolGuard(req.guards, req.autonomy)) {
      try {
        const sourceHome = req.env?.CODEX_HOME ?? process.env.CODEX_HOME ?? path.join(os.homedir(), ".codex");
        runHome = prepareCodexRunHome(req.guards.forbidCommands, req.cwd, sourceHome, this.inheritCodexAuth);
      } catch (error) {
        return {
          status: "ERROR",
          exitCode: null,
          text: "",
          usage: {},
          guards: guardReport(false, req.guards.exitChecks.length > 0, true),
          diagnostics: [
            `${CODEX_PERMISSION_PROFILE_UNAVAILABLE}: refusing guarded codex exec before spawn — ${String(error)}`,
          ],
        };
      }
    }

    // Two documented machine surfaces, used together:
    //   --json                    → stdout becomes a JSONL event stream (usage/model scanned tolerantly)
    //   -o/--output-last-message  → the final message lands in a file, independent of stream shape
    // The scratch files live in the OS temp dir: the orchestrator's own write, like
    // installation.yaml — never inside any guarded workspace root.
    const lastMessageFile = path.join(os.tmpdir(), `sta-codex-last-${process.pid}-${Date.now()}.txt`);
    let schemaFile: string | null = null;
    if (this.outputSchema) {
      schemaFile = path.join(os.tmpdir(), `sta-codex-schema-${process.pid}-${Date.now()}.json`);
      fs.writeFileSync(schemaFile, JSON.stringify(this.outputSchema), "utf8");
    }
    const args = [
      "exec",
      ...invocation.args,
      ...(runHome ? codexInlineGitHookArgs(runHome.path) : []),
      ...(req.modelExplicit && req.model ? ["--model", req.model] : []),
      ...(req.effort ? ["--config", `model_reasoning_effort=\"${req.effort}\"`] : []),
      "--json",
      ...(schemaFile ? ["--output-schema", schemaFile] : []),
      "-o",
      lastMessageFile,
      prompt,
    ];

    let proc: SpawnSyncReturns<string>;
    let resolvedThrough: string | null = null;
    try {
      ({ proc, resolvedThrough } = this.spawnResolved("codex", args, {
        cwd: req.cwd,
        encoding: "utf8",
        timeout: req.timeoutMs ?? this.defaultTimeoutMs,
        maxBuffer: 64 * 1024 * 1024,
        // Same channel as `claudeCodeAdapter.ts` — set unconditionally since it
        // costs nothing if the runtime never asks a guard to read it.
        env: {
          ...process.env,
          ...req.env,
          STA_ROLE: req.role,
          ...(runHome ? { CODEX_HOME: runHome.path } : {}),
        },
      }));
    } catch (e) {
      return { status: "UNAVAILABLE", exitCode: null, text: "", usage: {}, guards, diagnostics: [`failed to spawn \`codex\`: ${String(e)}`] };
    } finally {
      runHome?.cleanup();
    }

    if (proc.error) {
      const code = (proc.error as NodeJS.ErrnoException).code;
      if (code === "ENOENT") {
        const diagnostics = [`\`codex\` binary not found: ${proc.error.message}`];
        if (resolvedThrough === null && this.platform === "win32") {
          diagnostics.push(
            "on Windows an npm-installed `codex` is a .cmd/.ps1 shim spawnSync cannot execute; no resolvable entry was found — install the native build or expose a real executable on PATH",
          );
        }
        return { status: "UNAVAILABLE", exitCode: null, text: "", usage: {}, guards, diagnostics };
      }
      if (code === "ETIMEDOUT") {
        return { status: "TIMEOUT", exitCode: proc.status ?? null, text: "", usage: {}, guards, diagnostics: [`\`codex exec\` timed out: ${proc.error.message}`] };
      }
      return { status: "ERROR", exitCode: proc.status ?? null, text: "", usage: {}, guards, diagnostics: [`\`codex\` errored: ${proc.error.message}`] };
    }

    const stdout = proc.stdout ?? "";
    const stderr = proc.stderr ?? "";
    const failed = proc.status !== 0;

    // Final message: the `-o` file when Codex wrote one; otherwise fall back to
    // the previous behaviour (stdout/stderr as text) so a run against an older
    // or non-conforming CLI still returns something truthful. On schema runs the
    // same file holds the structured document — parsed when it parses, absent
    // (with a diagnostic) when it doesn't.
    let text: string;
    let structured: unknown;
    let structuredParseFailed = false;
    let lastMessageFileMissing = false;
    try {
      const fromFile = fs.readFileSync(lastMessageFile, "utf8");
      text = fromFile.length > 0 ? fromFile : stdout;
      if (schemaFile && fromFile.length > 0) {
        try {
          structured = JSON.parse(fromFile);
        } catch {
          structuredParseFailed = true;
        }
      }
    } catch {
      text = failed ? stderr || stdout : stdout;
      lastMessageFileMissing = true;
    } finally {
      try {
        fs.rmSync(lastMessageFile, { force: true });
      } catch {
        // best-effort cleanup of our own temp files
      }
      if (schemaFile) {
        try {
          fs.rmSync(schemaFile, { force: true });
        } catch {
          // best-effort cleanup of our own temp files
        }
      }
    }

    // Usage/model: whatever the JSONL events actually carried, nothing invented.
    const { usage, model } = parseCodexJsonl(stdout);

    const diagnostics: string[] = [];
    if (lastMessageFileMissing) {
      diagnostics.push("no -o/--output-last-message file was written; final message fell back to raw CLI output");
    }
    if (structuredParseFailed) {
      diagnostics.push("--output-schema was requested but the final message did not parse as JSON — structured is absent for this run");
    }
    // See PROVIDER_REFUSAL_PATTERN: a refusal to serve must not spend the
    // task's retry budget or trigger recovery for something the task did not
    // cause.
    if (failed && PROVIDER_REFUSAL_PATTERN.test(stderr)) {
      const line = stderr.split("\n").find((l) => PROVIDER_REFUSAL_PATTERN.test(l)) ?? "";
      return {
        status: "UNAVAILABLE",
        exitCode: proc.status ?? null,
        text: "",
        usage,
        model,
        guards,
        diagnostics: [...diagnostics, `\`codex\` provider refused to serve: ${line.trim()}`],
        raw: { stdout, stderr },
      };
    }

    return {
      status: failed ? "ERROR" : "OK",
      exitCode: proc.status ?? null,
      text,
      usage,
      // Only claimed when an event actually carried it — never guessed.
      model,
      guards,
      diagnostics,
      structured,
      raw: { stdout, stderr },
    };
  }
}

/** Per-run truth: native permissions cover pre-tool writes/commands; exit checks remain provider-neutral. */
function guardReport(preToolEnforced: boolean, wantsExitGuard: boolean, wantsPreToolGuard = preToolEnforced): RuntimeGuardReport {
  if (!wantsPreToolGuard && !wantsExitGuard) return { enforced: [], unenforced: [] };
  const enforced = preToolEnforced ? [RuntimeCapability.PRE_TOOL_GUARD] : [];
  const unenforced = [
    ...(!preToolEnforced && wantsPreToolGuard ? [RuntimeCapability.PRE_TOOL_GUARD] : []),
    ...(wantsExitGuard ? [RuntimeCapability.EXIT_GUARD, RuntimeCapability.PER_AGENT_EXIT_GUARD] : []),
  ];
  return {
    enforced,
    unenforced,
    reason: wantsExitGuard
      ? "Codex write/command scope is enforced by the per-run native permission profile and isolated execpolicy; exit checks are enforced by the provider-neutral runner"
      : undefined,
  };
}

/** A read-only OS sandbox makes write/command denial non-operative; every writable mode needs a real pre-tool guard. */
function requiresPreToolGuard(requested: RuntimeGuards, autonomy: RuntimeAutonomy): boolean {
  return autonomy !== "read-only" &&
    (requested.writeAllow.length > 0 || requested.writeDeny.length > 0 || requested.forbidCommands.length > 0);
}
