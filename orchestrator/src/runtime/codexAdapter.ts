/**
 * Pulls `developer_instructions` out of one of this framework's own
 * `.codex/agents/<role>.toml` bindings (OFF02 S6 schema, written by our
 * generator — see OFF03/P7). Hand-parsed on purpose: the file is generated by
 * us from a template we own, the same dependency-free reasoning the hooks and
 * their TS mirrors use. Supports the two shapes the generator emits — a TOML
 * multiline basic string (`"""…"""`) and a single-line basic string.
 *
 * Returns null when the key is absent or empty, so a malformed binding fails
 * loudly at the caller instead of sending an empty role definition to exec.
 */
export function extractDeveloperInstructions(toml: string): string | null {
  const multiline = toml.match(/developer_instructions\s*=\s*"""([\s\S]*?)"""/);
  if (multiline) {
    const value = multiline[1].replace(/\r\n/g, "\n").replace(/\\"""/g, '"""').trim();
    return value.length > 0 ? value : null;
  }
  const single = toml.match(/developer_instructions\s*=\s*"((?:[^"\\\n]|\\.)*)"\s*(?:#.*)?$/m);
  if (single) {
    const value = single[1].replace(/\\"/g, '"').replace(/\\n/g, "\n").trim();
    return value.length > 0 ? value : null;
  }
  return null;
}

/**
 * Tolerant reader over the documented `codex exec --json` JSONL event stream
 * (OFF02 S5 documents the event-type names; payload shapes beyond them are not
 * pinned down). Scans every parsed event and keeps the LAST numeric usage
 * fields / model string it actually finds — anything absent stays undefined,
 * per the absent ≠ 0 invariant. Never throws on a line it cannot parse.
 */
export function parseCodexJsonl(stdout: string): { usage: RuntimeUsage; model?: string } {
  let inputTokens: number | undefined;
  let outputTokens: number | undefined;
  let cachedInputTokens: number | undefined;
  let costUsd: number | undefined;
  let model: string | undefined;
  for (const line of stdout.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed.startsWith("{")) continue;
    let event: Record<string, unknown>;
    try {
      event = JSON.parse(trimmed) as Record<string, unknown>;
    } catch {
      continue;
    }
    const usage = event.usage as Record<string, unknown> | undefined;
    if (usage && typeof usage === "object") {
      if (typeof usage.input_tokens === "number") inputTokens = usage.input_tokens;
      if (typeof usage.output_tokens === "number") outputTokens = usage.output_tokens;
      // Current Codex JSONL uses `cached_input_tokens`; keep the older
      // `cache_read_input_tokens` spelling as a compatibility fallback.
      if (typeof usage.cached_input_tokens === "number") cachedInputTokens = usage.cached_input_tokens;
      else if (typeof usage.cache_read_input_tokens === "number") cachedInputTokens = usage.cache_read_input_tokens;
      // T-V8-012: no cache-*creation* counter has ever been observed in a Codex
      // JSONL event; `RuntimeUsage.cacheCreationInputTokens` stays unset here,
      // same absent-≠-0 posture as every other unconfirmed field on this adapter.
    }
    if (typeof event.total_cost_usd === "number") costUsd = event.total_cost_usd;
    if (typeof event.model === "string" && event.model.length > 0) model = event.model;
  }
  return {
    usage:
      inputTokens !== undefined || outputTokens !== undefined || cachedInputTokens !== undefined || costUsd !== undefined
        ? { inputTokens, outputTokens, cachedInputTokens, costUsd }
        : {},
    model,
  };
}

/**
 * The `RuntimeAdapter` for Codex — the second target `runtimeAdapter.ts` was
 * designed against, written to prove the interface is not Claude-Code-shaped
 * in disguise.
 *
 * **HEADLESS WRITES USE A PER-RUN NATIVE POLICY — INTERACTIVE CODEX DOES NOT.**
 *
 * V12 UAT exercised the invocation surfaces against real Codex CLI 0.154.0 and
 * 0.155.1 installs. The adapter now compiles every guarded headless run into a
 * custom native permission profile: broad read access, packet-scoped writes,
 * protected framework metadata, no network, an isolated execpolicy, and OS
 * deny rules for resolved forbidden executables such as Git. This is
 * intentionally the same host-native
 * security posture as the Claude adapter, not a container boundary.
 *
 * WHAT IS REASONABLY CONFIDENT
 * - `codex exec "<prompt>"` runs one non-interactive turn and exits — the shape
 *   `executeAgent` needs (a single request in, a single result out).
 * - Guarded writes use a custom permission profile rather than the legacy
 *   `--sandbox` modes. `codex exec` is non-interactive, so the adapter passes
 *   `approval_policy="never"` through `--config`.
 * - `AGENTS.md` (and a project `.codex/config.toml`) are Codex's project-level,
 *   committed configuration — the `PROJECT_LEVEL_BINDING` capability is claimed
 *   on that basis alone, not on any guard mechanism.
 *
 * WHAT IS NOT CLAIMED, AND WHY
 * - `NAMED_AGENTS` — Codex's *interactive* clients officially load custom agents
 *   from `.codex/agents/*.toml` (name/description/developer_instructions), and
 *   that `.toml` shape is exactly what this framework commits. What official
 *   docs do NOT document is an `exec`-level flag that
 *   selects a named agent for a headless run. Until one is documented, the role
 *   definition is still read here and folded into the prompt via documented
 *   flags only — which is why the capability stays unclaimed. Do not flip this
 *   to `true` without a confirmed native `exec` selector.
 * - `POST_TOOL_GUARD` / `EXIT_GUARD` / `PER_AGENT_EXIT_GUARD` — V12 UAT proved
 *   project hooks need a trust bypass, a crashing hook fails open, and Stop did
 *   not fire under `codex exec`. The adapter does not trust those hooks. It
 *   claims `PRE_TOOL_GUARD` only for the native permission/execpolicy boundary
 *   assembled by this adapter for the exact run; provider-neutral exit checks
 *   remain the runner's responsibility.
 * - `STRUCTURED_RESULT` — real-install UAT pinned the JSONL + output-schema
 *   round trip, so the normalised structured result is now a declared
 *   capability. `COST_REPORTING` remains unclaimed: no cost value is present.
 *   The adapter speaks two
 *   documented machine surfaces: `--json` (JSONL event stream) and `-o/--output-
 *   last-message` (final message written to a file). Token/model values are
 *   taken from event payloads **only where actually present** — payload shapes
 *   beyond the documented event-type names are not pinned down, so anything not
 *   found stays undefined rather than guessed (never a fabricated 0). That
 *   best-effort posture is still short of a claimable structured envelope.
 * - `INTERACTIVE_PROMPTS` — `codex exec` is explicitly non-interactive; a stage
 *   that needs to put a question to a person (`business-analyst`) cannot run
 *   through this adapter as designed. This is the same reasoning
 *   `runtimeCapabilities.ts`'s header already anticipated for `codex exec`.
 * - `models` — no default catalogue is declared. Guessing exact model ids here
 *   would be wild guessing; a caller that knows its installation's reachable
 *   models passes them via `CodexAdapterOptions.models`. Left empty,
 *   `RuntimeRegistry.reaching()` correctly reports that this runtime reaches
 *   nothing, rather than a fabricated answer that reaches everything.
 * - `PARALLEL_EXECUTION` — same as `claudeCodeAdapter.ts`: unclaimed by any
 *   adapter yet.
 */

